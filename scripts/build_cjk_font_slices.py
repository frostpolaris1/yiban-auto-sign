#: hanziDB 汉字频率序（去重后约 9,900 字）
FREQ_ORDER = "".join(_FREQ_RAW.split())
#: 《通用规范汉字表》一/二/三级字表序（去重后 8,105 字）
STD_ORDER = "".join(_STD_RAW.split())


def _ranges(codepoints):
    """把码点集合合并为最少区间，产出 CSS unicode-range 片段列表。"""
    out = []
    cps = sorted(codepoints)
    if not cps:
        return out
    start = prev = cps[0]
    for cp in cps[1:]:
        if cp == prev + 1:
            prev = cp
            continue
        out.append((start, prev))
        start = prev = cp
    out.append((start, prev))
    return [
        "U+%04X" % a if a == b else "U+%04X-%04X" % (a, b) for a, b in out
    ]


def _chunk(items, size):
    return [items[i:i + size] for i in range(0, len(items), size)]


def read_project_codepoints(pattern):
    """读取模板文件中的全部码点，作为「项目字频」热区。"""
    cps = set()
    files = sorted(glob.glob(pattern, recursive=True))
    for path in files:
        with open(path, encoding="utf-8") as fh:
            for ch in fh.read():
                cps.add(ord(ch))
    return cps, files


def build_slices(cmap, project_cps, hot_size, freq_size, rest_size, freq_top):
    """按覆盖区 + 优先级排序后切片，返回 [(tag, [codepoints]), ...]。

    groups[0] 项目字频热区（模板实际用字，频率序）
    groups[1] hanziDB 高频区（rank < freq_top，频率序）
    groups[2] 其余按码点连续排列（便于 unicode-range 合并）
    """
    basic_lo, basic_hi = BLOCKS["basic"]
    punct_lo, punct_hi = BLOCKS["punct"]
    full_lo, full_hi = BLOCKS["fullwidth"]
    exta_lo, exta_hi = BLOCKS["exta"]

    std_set = set(STD_ORDER)
    # 覆盖集合：基本区 + 标点 + 全角（字体含字形者）∪ 规范字表收录的扩展 A
    covered = {
        cp for cp in cmap
        if basic_lo <= cp <= basic_hi
        or punct_lo <= cp <= punct_hi
        or full_lo <= cp <= full_hi
    }
    covered |= {
        cp for cp in cmap
        if exta_lo <= cp <= exta_hi and chr(cp) in std_set
    }

    freq_rank = {ch: i for i, ch in enumerate(FREQ_ORDER)}

    groups = {0: [], 1: [], 2: []}
    for cp in covered:
        ch = chr(cp)
        if cp in project_cps:
            groups[0].append(cp)
        elif ch in freq_rank and freq_rank[ch] < freq_top:
            groups[1].append(cp)
        else:
            groups[2].append(cp)

    big = len(FREQ_ORDER) + 1
    groups[0].sort(key=lambda cp: (freq_rank.get(chr(cp), big), cp))
    groups[1].sort(key=lambda cp: (freq_rank[chr(cp)], cp))
    groups[2].sort()

    slices = []
    for tag, items, size in (
        ("hot", groups[0], hot_size),
        ("freq", groups[1], freq_size),
        ("rest", groups[2], rest_size),
    ):
        for part in _chunk(items, size):
            slices.append((tag, part))
    return slices, groups, covered


def instantiate_static(font_path, weight, out_path):
    """从可变字体实例化静态字重。"""
    font = TTFont(font_path)
    if "fvar" in font:
        instancer.instantiateVariableFont(
            font, {"wght": weight}, inplace=True, updateFontNames=False
        )
    if "OS/2" in font:
        font["OS/2"].usWeightClass = weight
    font.save(out_path)
    font.close()


def _has_cff(font_path):
    font = TTFont(font_path, lazy=True)
    try:
        return "CFF " in font or "CFF2" in font
    finally:
        font.close()


def otf_to_ttf(src_path, out_path, max_err=1.0):
    """CFF/OTF → glyf/TTF：用 cu2qu 把三次曲线转为二次曲线。

    同形同覆盖下，woff2 对 CFF 的压缩明显差于 glyf（本项目实测单页载荷高约 35%），
    故切片前统一转为 glyf。转换只影响曲线的数学表达（cu2qu 近似），视觉一致。
    """
    from fontTools.pens.cu2quPen import Cu2QuPen
    from fontTools.pens.ttGlyphPen import TTGlyphPen

    font = TTFont(src_path)
    glyph_order = font.getGlyphOrder()
    glyph_set = font.getGlyphSet()
    glyf = newTable("glyf")
    glyf.glyphOrder = glyph_order
    glyf.glyphs = {}
    for name in glyph_order:
        pen = TTGlyphPen(glyph_set)
        glyph_set[name].draw(Cu2QuPen(pen, max_err, reverse_direction=True))
        glyf[name] = pen.glyph()
    font["glyf"] = glyf
    font["loca"] = newTable("loca")
    for name in glyph_order:
        glyf[name].recalcBounds(glyf)
    maxp = font["maxp"]
    maxp.tableVersion = 0x00010000
    maxp.recalc(font)
    maxp.maxZones = 1
    maxp.maxTwilightPoints = 0
    maxp.maxStorage = 0
    maxp.maxFunctionDefs = 0
    maxp.maxInstructionDefs = 0
    maxp.maxStackElements = 0
    maxp.maxSizeOfInstructions = 0
    font["head"].indexToLocFormat = 1
    font["head"].glyphDataFormat = 0
    font["post"].formatType = 3.0
    del font["CFF "]
    font.sfntVersion = "\x00\x01\x00\x00"
    font.save(out_path)
    font.close()


def ensure_glyf_source(path, workdir, weight, max_err):
    """若为 CFF/OTF 源则转成 glyf/TTF（切片前统一轮廓类型）。"""
    if not _has_cff(path):
        return path
    out = os.path.join(workdir, "NotoSansSC-%d-glyf.ttf" % weight)
    print("  CFF/OTF 源转 glyf/TTF（cu2qu max_err=%s）…" % max_err)
    otf_to_ttf(path, out, max_err)
    return out


def subset_to_woff2(src_path, codepoints, out_path):
    """用 pyftsubset 产出 woff2；CJK 正文不需要 OpenType 布局特性。"""
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = []
    opts.drop_tables = [*opts.drop_tables, "vhea", "vmtx", "VORG", "VVAR"]
    opts.recalc_bounds = False
    font = subset.load_font(src_path, opts)
    try:
        s = subset.Subsetter(options=opts)
        s.populate(unicodes=codepoints)
        s.subset(font)
        if "head" in font:  # 固定时间戳，保证产物字节级可复现
            font["head"].created = HEAD_TIMESTAMP
            font["head"].modified = HEAD_TIMESTAMP
        subset.save_font(font, out_path, opts)
    finally:
        font.close()


CSS_HEADER = """/* Self-hosted %(family)s. %(faces)d faces (%(weights)s).
 * 由 scripts/build_cjk_font_slices.py 从上游完整字体按字频重切片生成。
 * 来源 / 构建方式 / 哈希基线：../MANIFEST.md。
 * License: SIL Open Font License 1.1 (see ../OFL.txt)。不要手工编辑。
 * 生成后由 scripts/stamp_font_versions.py 给 url() 追加内容哈希 ?v=（幂等）。
 */
"""


def write_css(css_path, by_weight):
    total_faces = sum(len(v) for v in by_weight.values())
    weights = ", ".join(str(w) for w in sorted(by_weight))
    parts = [CSS_HEADER % {"family": FAMILY, "faces": total_faces, "weights": weights}]
    for weight in sorted(by_weight):
        for fname, cps in by_weight[weight]:
            parts.append(
                "@font-face {\n"
                "  font-family: '%s';\n"
                "  font-style: normal;\n"
                "  font-weight: %d;\n"
                "  font-display: swap;\n"
                "  src: url('%s') format('woff2');\n"
                "  unicode-range: %s;\n"
                "}\n" % (FAMILY, weight, fname, ", ".join(_ranges(cps)))
            )
    with open(css_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(parts))


def parse_weight_sources(items):
    """解析 --weight-font 的 W=PATH 列表。"""
    out = {}
    for item in items:
        if "=" not in item:
            sys.exit("错误：--weight-font 需要 W=PATH 形式：%s" % item)
        weight, path = item.split("=", 1)
        out[int(weight)] = path
    return out


def verify_weight_source(weight, path, strict):
    """校验静态字重源是否命中记录的上游文件与 SHA-256。"""
    name = os.path.basename(path)
    rec = UPSTREAM_WEIGHT_FILES.get(weight)
    digest = sha256_file(path)
    if rec and name == rec[0]:
        if digest == rec[1]:
            print("字重 %d 源 SHA-256 校验通过：%s" % (weight, name))
            return
        msg = ("字重 %d 源 %s SHA-256=%s 与记录 %s 不一致"
               % (weight, name, digest, rec[1]))
        if strict:
            sys.exit("错误：" + msg)
        print("警告：" + msg)
        return
    if strict:
        recorded = ", ".join(v[0] for v in UPSTREAM_WEIGHT_FILES.values())
        sys.exit("错误：字重 %d 源 %s 不在上游记录表（%s）中" % (weight, name, recorded))
    print("警告：字重 %d 源 %s 未经上游哈希校验（--strict-source 可强制）" % (weight, name))


#: 允许被整目录替换（`shutil.rmtree` + `os.replace`）的输出根，相对仓库根。
#: outdir 是位置参数、随后直接 rmtree，接受任意路径意味着一次笔误
#: （漏写一层目录、变量为空、补全选错）就是不可逆的目录删除。
OUTDIR_WHITELIST = ("web/static",)


def resolve_outdir(path):
    """把 outdir 解析为绝对路径并校验落在仓库白名单内；不在则抛 ValueError。

    判包含关系用 `commonpath` 而非字符串前缀——前缀会把 `web/static-evil`
    误判为合法。白名单根自身也拒绝：`rmtree(web/static)` 不是任何一次切片该做的事。
    """
    root = os.path.realpath(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    target = os.path.realpath(path)
    for rel in OUTDIR_WHITELIST:
        allowed = os.path.join(root, *rel.split("/"))
        try:
            inside = os.path.commonpath([target, allowed]) == allowed
        except ValueError:          # 不同盘符（Windows）：必然不在白名单内
            continue
        if inside and target != allowed:
            return target
    raise ValueError(
        "输出目录不在白名单内：%s（仅允许仓库内 %s 之下的子目录）"
        % (path, "、".join(OUTDIR_WHITELIST))
    )


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("outdir", nargs="?", help="输出目录（整目录原子替换）")
    ap.add_argument("--fetch", metavar="DIR",
                    help="仅从 npm 上游取回各字重字体到 DIR 后退出（与切片分离）")
    ap.add_argument("--font", help="完整可变字体路径（各字重由 instancer 实例化）")
    ap.add_argument("--weight-font", action="append", default=[], metavar="W=PATH",
                    help="各字重静态字体源，可重复（如 --weight-font 400=Regular.otf）")
    ap.add_argument("--weights", default="400,700", help="字重列表，默认 400,700")
    ap.add_argument("--project-glob", default="web/templates/**/*.html",
                    help="项目模板 glob（项目字频热区来源）")
    ap.add_argument("--hot-size", type=int, default=300, help="项目字频热区分片码点数")
    ap.add_argument("--freq-size", type=int, default=300, help="hanziDB 高频区分片码点数")
    ap.add_argument("--rest-size", type=int, default=500, help="其余（按码点）分片码点数")
    ap.add_argument("--freq-top", type=int, default=3000,
                    help="hanziDB 频率序纳入高频区的字数，默认 3000")
    ap.add_argument("--css-name", default="notosanssc.css", help="产出 CSS 文件名")
    ap.add_argument("--max-err", type=float, default=1.0,
                    help="CFF→glyf 时 cu2qu 的最大近似误差（字体单位，默认 1.0）")
    ap.add_argument("--strict-source", action="store_true",
                    help="上游文件 SHA-256 不匹配则中止")
    args = ap.parse_args(argv)

    if args.fetch:
        fetch_upstream(args.fetch)
        return 0

    if not args.outdir:
        ap.error("需要输出目录（--fetch 模式除外）")
    try:
        args.outdir = resolve_outdir(args.outdir)
    except ValueError as e:
        ap.error(str(e))
    weights = [int(w) for w in args.weights.split(",") if w.strip()]
    weight_sources = parse_weight_sources(args.weight_font)
    if args.font and weight_sources:
        ap.error("--font 与 --weight-font 不能同时使用")
    if not args.font and not weight_sources:
        ap.error("需要 --font（可变字体）或 --weight-font W=PATH（各字重静态字体）")
    if weight_sources:
        missing = [w for w in weights if w not in weight_sources]
        if missing:
            ap.error("缺少字重字体源：%s" % ", ".join(str(w) for w in missing))

    for weight in weights:
        if weight_sources:
            verify_weight_source(weight, weight_sources[weight], args.strict_source)
        else:
            print("字重 %d：由 %s 实例化" % (weight, args.font))

    project_cps, project_files = read_project_codepoints(args.project_glob)
    print("项目模板：%d 个文件，%d 个不同码点" % (len(project_files), len(project_cps)))

    cmap_source = args.font or weight_sources[weights[0]]
    font = TTFont(cmap_source, lazy=True)
    cmap = set(font.getBestCmap())
    slices, groups, covered = build_slices(
        cmap, project_cps, args.hot_size, args.freq_size, args.rest_size, args.freq_top
    )
    font.close()

    print("覆盖集合：%d 个码点（基本区 %d / 标点 %d / 全角 %d / 扩展A常用 %d）" % (
        len(covered),
        sum(1 for c in covered if BLOCKS["basic"][0] <= c <= BLOCKS["basic"][1]),
        sum(1 for c in covered if BLOCKS["punct"][0] <= c <= BLOCKS["punct"][1]),
        sum(1 for c in covered if BLOCKS["fullwidth"][0] <= c <= BLOCKS["fullwidth"][1]),
        sum(1 for c in covered if BLOCKS["exta"][0] <= c <= BLOCKS["exta"][1]),
    ))
    print("分组：hot=%d freq=%d rest=%d；共 %d 片/字重" % (
        len(groups[0]), len(groups[1]), len(groups[2]), len(slices)))

    staging = args.outdir.rstrip("/\\") + ".build-%d" % os.getpid()
    workdir = tempfile.mkdtemp(prefix="notosanssc-build-")
    os.makedirs(staging, exist_ok=True)
    by_weight = {}
    try:
        for weight in weights:
            if weight_sources:
                src = weight_sources[weight]
            else:
                src = os.path.join(workdir, "NotoSansSC-%d.ttf" % weight)
                instantiate_static(args.font, weight, src)
            static = ensure_glyf_source(src, workdir, weight, args.max_err)
            faces = []
            total = 0
            for idx, (_tag, cps) in enumerate(slices):
                fname = "noto-sans-sc-%d-%03d.woff2" % (weight, idx)
                out = os.path.join(staging, fname)
                subset_to_woff2(static, cps, out)
                size = os.path.getsize(out)
                total += size
                faces.append((fname, cps))
                print("  w%d %-48s %5d cp %8d B" % (weight, fname, len(cps), size))
            by_weight[weight] = faces
            print("字重 %d：%d 片，合计 %d 字节" % (weight, len(faces), total))
        write_css(os.path.join(staging, args.css_name), by_weight)
    finally:
        shutil.rmtree(workdir, ignore_errors=True)

    # woff2 魔数校验
    for fn in sorted(os.listdir(staging)):
        if fn.endswith(".woff2"):
            with open(os.path.join(staging, fn), "rb") as fh:
                if fh.read(4) != b"wOF2":
                    sys.exit("错误：%s 不是合法 woff2" % fn)

    # 整目录原子替换（旧分片不保留，避免新旧混放）
    if os.path.isdir(args.outdir):
        shutil.rmtree(args.outdir)
    elif os.path.exists(args.outdir):
        os.remove(args.outdir)
    os.replace(staging, args.outdir)

    css_path = os.path.join(args.outdir, args.css_name)
    woff2_files = [f for f in os.listdir(args.outdir) if f.endswith(".woff2")]
    total_bytes = sum(os.path.getsize(os.path.join(args.outdir, f)) for f in woff2_files)
    print("完成：%s" % args.outdir)
    print("  woff2 %d 个，合计 %d 字节；CSS %d 字节" % (
        len(woff2_files), total_bytes, os.path.getsize(css_path)))

    # 生成后立刻给 url() 打内容哈希版本（幂等）：分片内容一变 URL 即变。
    # 强缓存下的失效路径靠它 + 三个外壳给子 CSS 的 ?v={{web_version}} 共同打断——
    # 重切片后旧访客不再引用已删除的旧分片（详见 scripts/stamp_font_versions.py 头注释）。
    # fonts 根目录存在 fonts.css（现为纯注释说明/scope 哨兵）时对整个 fonts 目录打标
    # （本脚本的常规落点），否则只打产出目录自身（独立 staging 场景）。
    import stamp_font_versions
    fonts_root = os.path.dirname(os.path.abspath(args.outdir))
    scope = fonts_root if os.path.isfile(os.path.join(fonts_root, "fonts.css")) else args.outdir
    for rel, changed in sorted(stamp_font_versions.stamp_fonts_dir(scope).items()):
        if changed:
            print("  版本打标：%s" % rel)
    return 0


