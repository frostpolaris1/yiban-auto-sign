"""web 面的进程内文本缓存：更新日志全文与全站公告的**已发布**文本各占一格。

**功能**
持有两个单格缓存（`[0]` 是唯一槽位，初值 `None` 表示尚未读取）：
`_changelog_cache` 存项目根 `CHANGELOG.md` 的全文；
`_announcement_cache` 存 `.env` 里 `YIBAN_ANNOUNCEMENT` 的已发布文本。
两者只存对外文本，不存任何凭据、路径或会话事实。

**归属**
原 `web/app.py` 的两个模块级缓存，旧名同为 `_changelog_cache` /
`_announcement_cache`，形态同为 `[文本]` 单格列表。批 3-c S2 把它们搬到本模块，
唯一真源在此；`web/app.py` 不再持有这两个名字。
读者 `web/routes/settings_api.py` 与新家直连，不经 `web.routes.appmod()` 取。

**复用**
更新日志与公告的两条读路由读本模块；公告的双人发布路由写 `_announcement_cache`。
每个缓存的读点各一处，故本模块不另建访问器：多一层包装只会多一个可漂移的面。

**不变量**
① 两个缓存都是**进程内**对象。web 固定 `-w 1` 是明文设计不变量，
进程内即全局；本模块不得改成跨进程共享、也不得落盘。
② **公告草稿不进缓存**：草稿按会话现读，缓存它等于把"尚不成立的事实"
广播给所有匿名请求。
③ **更新日志启动后缓存、重启失效**：首次读取即固定，部署重启自然重读。
④ 缓存不因路由或测试的改写而重建：`[0]` 的读-改-写就是唯一更新路径。

**通信**
本模块**不导入** `web.app`，也不读 `.env`、不读文件：取值与落值全由调用方完成。
这样测试打桩落在调用方（`read_env`、`open`）上即可，本模块不自持可被架空的绑定。
"""

