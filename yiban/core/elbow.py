"""领取肘界谓词（elbow）：领域核心层（core）的纯函数。

**一句话**：给定一行的到期时刻、当前时刻与该角色的肘界，答"该行现在是否轮到本角色领"。

**为什么有它**（docs/refactor/130 第 3.3 节；工单 l1rx 第二刀）：兜底常驻只该领"已经
过期很久"的行，不与该轮计划抢新到点的活。把"谁该做"变成**行的函数**（这行到期多久），
而不是**进程身份的函数**，10-07 型启动竞态便从机制上消失——零协调。现役让位探针只是
轮内止损，起跑胜负未变。

**硬约束（本模块存在的理由）**
- 纯函数：同一输入必得同一输出；不读全局可变状态。
- 时钟由调用方注入（形参 `now`）：本模块**不**取时钟、**不**读环境变量、**不**读文件、
  **不**用随机数。故不 import 任何 I/O、时钟或随机模块（由 tests/test_elbow_predicate.py
  的 AST 守卫钉死）。
- 只实现 `elbow` 这一维。角色描述与行描述是**冻结值对象**；将来加 `scope`/`tier` 维时，
  在对象上加字段、在本函数里加判据即可，**调用点不变**（接缝）。

**判定语义（单义）**

    该行可领  ⇔  行到期时刻 ≤ 当前时刻 − 该角色肘界

即"已经过期达到或超过肘界"。这是**闭区间**：恰好等于肘界算可领（与领取谓词
`到期时刻 <= 当前时刻 - 肘界` 同形）。

**时间域**：`run_at` 与 `now` 均为 **epoch 秒（float）**。本模块不解析时间串；把台账里
的毫秒时间串解析成 epoch 秒是**适配器**的职责。

**边界（逐条写清，各有测试）**
- 恰好等于肘界（`run_at == now - elbow`）：可领（闭区间）。
- 到期在未来（`run_at > now`，肘界 ≥ 0）：不可领。
- 肘界为 0：退化为"到期即可领"（`run_at <= now`），即定时执行体的语义。
- 时钟回退（`now` 变小）：本函数无状态，重算只会**收回**可领结论，绝不提前授予
  ⇒ 方向 fail-closed。对固定行与肘界，结论随 `now` 单调不减。
- 肘界为负：算术仍有定义（变成"允许领到期前 |肘界| 秒的行"）。**负肘界不是合法角色
  配置**，本模块不夹取、不抛错，如实按算术判定；配置合法性校验属应用层职责。
"""
from __future__ import annotations

from dataclasses import dataclass

__all__ = ["ClaimRole", "ClaimRow", "may_claim"]


@dataclass(frozen=True)
class ClaimRow:
    """参与领取判定的一行任务。

    本批只带到期时刻一维；`vshard` / `result`（scope 与 tier 维要读的行属性）留待后续
    批次在本对象上加字段，届时调用点不改造型。
    """

    #: 行的到期时刻（epoch 秒）——台账 `sign_tasks.run_at` 经适配器解析得来。
    run_at: float


@dataclass(frozen=True)
class ClaimRole:
    """领取角色的描述（"角色即数据"）。

    本批只有肘界一维；`scope` / `tier` 留作接缝，后续批次在本对象上加字段。
    """

    #: 肘界（秒）。0 = 定时执行体（到期即领）；正数 = 只领过期达到该时长的行。
    elbow_sec: float = 0.0


def may_claim(row: ClaimRow, role: ClaimRole, now: float) -> bool:
    """该行现在是否轮到本角色领（判定语义与边界见模块说明）。

    `now` 由调用方注入（本模块不取时钟）。返回 True = 可领（本角色此刻接手该行）。
    """
    return row.run_at <= now - role.elbow_sec
